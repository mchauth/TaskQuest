# --- the datum --------------------------------------------------------------------------------
def _runs(row):
    out, s = [], None
    for i, v in enumerate(row):
        if v and s is None:
            s = i
        elif not v and s is not None:
            out.append((s, i - 1))
            s = None
    if s is not None:
        out.append((s, len(row) - 1))
    return out


def crown_of(mask):
    """The wearer's skull crown in one frame: (y, x), x rounded to the pixel grid.

    NOT the topmost pixel of the silhouette. In the cheer frames both hands are raised ABOVE the
    head, so the top row of the wearer is a pair of fists — see THE RENDER-PAID LESSONS. What is
    looked for instead is the skull's own shape: a short run with nothing above it that widens by
    one pixel each side on each of the next two rows.
    """
    ys, _ = np.nonzero(mask)
    if len(ys) == 0:
        return None
    for y in range(int(ys.min()), min(mask.shape[0] - 2, 44)):
        for a, b in _runs(mask[y]):
            if not (CROWN_W[0] <= b - a + 1 <= CROWN_W[1]):
                continue
            if y > 0 and mask[y - 1, a:b + 1].any():
                continue
            if not mask[y + 1, max(a - 1, 0):b + 2].all():
                continue
            if not mask[y + 2, max(a - 2, 0):b + 3].all():
                continue
            # x is rounded to the grid: a crown of even width sits on a half pixel, and a
            # half-pixel origin would put every lattice unit on a half pixel too. The rounding
            # is a half-pixel shift of the whole ornament on those four frames and nothing else.
            return y, int(round((a + b) / 2.0))
    return None


_DATUM_CACHE = {}


def datum_table(gender):
    """(y, x) of the wearer's crown for every active frame. THE origin of this axis."""
    if gender in _DATUM_CACHE:
        return _DATUM_CACHE[gender]
    sheet = load(SKIN[gender])
    out = {}
    for fi in range(ACTIVE):
        r, c = fi // COLS, fi % COLS
        m = sheet[r * FH:(r + 1) * FH, c * FW:(c + 1) * FW, 3] > 0
        if not m.any():
            continue
        cr = crown_of(m)
        if cr is not None:
            out[fi] = cr
    _DATUM_CACHE[gender] = out
    return out


def phase_of(datum):
    """The lattice phase a datum implies: u_sheet(x,y) - u(x,y) is constant and equal to this."""
    yd, xd = datum
    return (A * xd + B * yd) % P


# --- painting ---------------------------------------------------------------------------------
def u_sheet(ys, xs):
    """The lattice coordinate in SHEET units — no datum in it. The datum is one subtraction away,
    which is the whole of the difference between this axis and the FRAME-ANCHORED control."""
    return A * xs.astype(np.int64) + B * ys.astype(np.int64)


def paint(fr, mask, stops, phase):
    """Paint the lattice onto every opaque pixel of `mask`. No component labelling: a pixel is
    told its role by its coordinates and the wearer's crown, and needs to know nothing else."""
    ys, xs = np.nonzero(mask)
    if len(ys) == 0:
        return 0
    u = (u_sheet(ys, xs) - phase) % P
    for i in range(len(ys)):
        fr[ys[i], xs[i], :3] = stops[PROFILE[int(u[i])]]
        fr[ys[i], xs[i], 3] = 255
    return len(ys)


def put(fr, y, x, rgb):
    if 0 <= y < FH and 0 <= x < FW:
        fr[y, x, :3] = rgb
        fr[y, x, 3] = 255


def recolor(src, fr, a, D, M, L):
    v = src[..., :3].astype(np.float32).max(-1) / 255.0
    vref = float(np.median(v[a]))
    ratio = v / max(vref, 1e-3)
    for y, x in np.argwhere(a):
        q = ratio[y, x]
        put(fr, y, x, D if q < Q_LO else (L if q > Q_HI else M))


# --- the controls -----------------------------------------------------------------------------
CONTROLS = ('self-anchored', 'frame-anchored', 'per-slot-pitch', 'horizontal', 'random-phase')


def control_phase(mode, fi, gender, mask, slot, rng=None):
    """The phase each control would use for this component/frame. Returns (phase, A, B, P)."""
    if mode == 'self-anchored':                 # what all sixty-one prior axes do
        ys, xs = np.nonzero(mask)
        yd = int(ys.min())
        xd = int(round((int(xs.min()) + int(xs.max())) / 2.0))
        return (A * xd + B * yd) % P, A, B, P
    if mode == 'frame-anchored':                # the canvas corner; registers, but crawls
        return 0, A, B, P
    if mode == 'per-slot-pitch':                # the adaptive-boundary rule, fatal here
        p = {'chest': 10, 'legs': 8, 'boots': 6, 'helmet': 12}[slot]
        d = datum_table(gender).get(fi)
        return ((A * d[1] + B * d[0]) % p if d else 0), A, B, p
    if mode == 'horizontal':                    # registered, but a level line proves nothing
        d = datum_table(gender).get(fi)
        return ((0 * d[1] + B * d[0]) % P if d else 0), 0, B, P
    if mode == 'random-phase':
        return int(rng.integers(0, P)), A, B, P
    raise ValueError(mode)


def paint_mode(fr, mask, stops, fi, gender, slot, mode, rng=None):
    if mode is None:
        d = datum_table(gender).get(fi)
        if d is None:
            return 0
        return paint(fr, mask, stops, phase_of(d))
    if mode == 'self-anchored':
        # per COMPONENT, because that is exactly what the sixty-one prior axes do: each piece is
        # its own world. Painting the whole frame from the union bounding box would be a weaker
        # control and it scored 0.577 on EXTERNAL instead of the 1.000 it must score.
        lbl, n = label4(mask)
        tot = 0
        for k in range(1, n + 1):
            m = lbl == k
            if m.sum() < 4:
                continue
            tot += paint(fr, m, stops, self_phase(m))
        return tot
    ph, a, b, p = control_phase(mode, fi, gender, mask, slot, rng)
    ys, xs = np.nonzero(mask)
    if len(ys) == 0:
        return 0
    u = (a * xs.astype(np.int64) + b * ys.astype(np.int64) - ph) % p
    prof = [PROFILE[int(round(k * P / float(p)))] for k in range(p)]
    for i in range(len(ys)):
        fr[ys[i], xs[i], :3] = stops[prof[int(u[i])]]
        fr[ys[i], xs[i], 3] = 255
    return len(ys)


# --- sheet machinery --------------------------------------------------------------------------
def label4(mask):
    """Self-contained 4-connectivity labelling (scipy-free). Used ONLY by the acceptance test and
    the diagnostics — the generator itself never segments anything."""
    h, w = mask.shape
    labels = np.zeros((h, w), dtype=np.int32)
    n = 0
    stack = []
    for sy in range(h):
        for sx in range(w):
            if mask[sy, sx] and labels[sy, sx] == 0:
                n += 1
                labels[sy, sx] = n
                stack.append((sy, sx))
                while stack:
                    y, x = stack.pop()
                    for ny, nx in ((y - 1, x), (y + 1, x), (y, x - 1), (y, x + 1)):
                        if 0 <= ny < h and 0 <= nx < w and mask[ny, nx] and labels[ny, nx] == 0:
                            labels[ny, nx] = n
                            stack.append((ny, nx))
    return labels, n


def load_any(fname):
    if os.path.exists(os.path.join(CHAR, fname)):
        return load(fname)
    if fname.endswith('_f.png'):
        return load(fname[:-6] + '.png')
    raise FileNotFoundError(fname)


def build(base, cls, gender, slot, mode=None, seed=0):
    D, M, L = BODY[cls]
    stops = DATUMPAL[cls]
    # the RANDOM-PHASE control must draw INDEPENDENTLY per slot. Seeded from the slot as well as
    # from `seed` because a generator that draws the same sequence in every slot is not a random
    # control at all — it is a synchronised one, and it passed SEAMLESS the first time it was run.
    rng = np.random.default_rng(seed * 10 + list(SLOTS).index(slot))
    out = np.zeros_like(base)
    for fi in range(NFR):
        r, c = fi // COLS, fi % COLS
        sl = (slice(r * FH, (r + 1) * FH), slice(c * FW, (c + 1) * FW))
        src = base[sl]
        a = src[..., 3] > 0
        if not a.any():
            continue
        fr = out[sl]
        recolor(src, fr, a, D, M, L)
        if fi >= ACTIVE:
            continue
        paint_mode(fr, a, stops, fi, gender, slot, mode, rng)
    return out


# ---------------------------------------------------------------------------------------------
# THE ACCEPTANCE TEST — a REGISTRATION.
#
# The phase is ESTIMATED off the painted pixels of a sheet, with no reference to the datum that
# produced them: for each of the P possible phases, count how many pixels carry the role that
# phase would give them, and take the argmax. That estimate is then compared with the datum's.
# Estimating rather than assuming is what makes clause 2 a real statement — the four slot sheets
# are asked independently what world they think they are in.
# ---------------------------------------------------------------------------------------------
# Clause 3's threshold. Chance is 1/P = 0.100 and the SELF-ANCHORED control is 1.000 BY
# CONSTRUCTION, so the discriminating value is anywhere between; it is set midway rather than
# tight to the observed 0.156, because a threshold tuned to the observation is not a test.
EXT_MAX = 0.50


def read_roles(fr, mask, stops):
    ys, xs = np.nonzero(mask)
    px = fr[ys, xs, :3].astype(np.int32)
    pal = np.array(stops, dtype=np.int32)
    return ys, xs, ((px[:, None, :] - pal[None, :, :]) ** 2).sum(-1).argmin(1)


def estimate_phase(fr, mask, stops, lat=None):
    """(best phase, agreement fraction) read off the pixels alone.

    `lat` is the (a, b, p, profile) the reader assumes. It is a parameter and not the module
    constant because the CONTROLS must be read on their own lattice: a control read through this
    axis's lattice would fail everything for the uninteresting reason that the reader cannot see
    it, and the whole value of a control is that it fails for its OWN reason.
    """
    a, b, p, prof = lat if lat else (A, B, P, PROFILE)
    ys, xs, role = read_roles(fr, mask, stops)
    if len(ys) == 0:
        return None, 0.0
    u0 = a * xs.astype(np.int64) + b * ys.astype(np.int64)
    prof = np.array(prof)
    best, bestn = 0, -1
    for ph in range(p):
        want = prof[(u0 - ph) % p]
        n = int((want == role).sum())
        if n > bestn:
            best, bestn = ph, n
    return best, bestn / float(len(ys))


def self_phase(mask, lat=None):
    """The phase this component would have chosen for itself — i.e. what all sixty-one prior axes
    would do: origin at the piece's own top edge and horizontal centre."""
    a, b, p = (lat[0], lat[1], lat[2]) if lat else (A, B, P)
    ys, xs = np.nonzero(mask)
    yd = int(ys.min())
    xd = int(round((int(xs.min()) + int(xs.max())) / 2.0))
    return (a * xd + b * yd) % p


def accept_all(verbose=True):
    """The five clauses over all 24 sheets, every active frame, every component."""
    nsheet = ncomp = nbad = 0
    seam_ok = seam_tot = 0
    ext_hit = ext_tot = 0
    body_res = set()
    sheet_phases = set()
    lattices = set()
    per_frame_phase = {}                     # (cls, gender, fi) -> {slot: phase}
    firsts = []

    for slot, cfg in SLOTS.items():
        for cls, stem in cfg['srcs'].items():
            for gender, suffix in (('m', ''), ('f', '_f')):
                base = load_any('%s%s.png' % (stem, suffix))
                arr = build(base, cls, gender, slot)
                nsheet += 1
                stops = DATUMPAL[cls]
                dt = datum_table(gender)
                for fi in range(ACTIVE):
                    r, c = fi // COLS, fi % COLS
                    sl = (slice(r * FH, (r + 1) * FH), slice(c * FW, (c + 1) * FW))
                    a = base[sl][..., 3] > 0
                    if not a.any() or fi not in dt:
                        continue
                    fr = arr[sl]
                    want = phase_of(dt[fi])
                    lattices.add((A, B, P))

                    # (1) ON-LATTICE, per component
                    lbl, n = label4(a)
                    for k in range(1, n + 1):
                        m = lbl == k
                        if m.sum() < 4:
                            continue
                        ncomp += 1
                        ys, xs, role = read_roles(fr, m, stops)
                        prof = np.array(PROFILE)
                        got = prof[(u_sheet(ys, xs) - want) % P]
                        bad = int((got != role).sum())
                        if bad:
                            nbad += 1
                            if len(firsts) < 10:
                                firsts.append('ON-LATTICE %s %s%s f%d comp%d: %d/%d px off'
                                              % (slot, cls, suffix, fi, k, bad, len(ys)))
                        # (3) EXTERNAL — would the piece's own origin have produced this?
                        ext_tot += 1
                        if self_phase(m) == want:
                            ext_hit += 1

                    # (2) SEAMLESS — phase estimated off THIS sheet alone
                    est, agree = estimate_phase(fr, a, stops)
                    per_frame_phase.setdefault((cls, gender, fi), {})[slot] = est
                    seam_tot += 1
                    if est == want and agree > 0.999:
                        seam_ok += 1
                    elif len(firsts) < 10:
                        firsts.append('SEAMLESS %s %s%s f%d: estimated %s, datum says %s (%.3f)'
                                      % (slot, cls, suffix, fi, est, want, agree))

                    # (4) BODY-TRACKING — the residual in body coordinates
                    body_res.add((est - want) % P)
                    sheet_phases.add(est)

    agree_slots = sum(1 for v in per_frame_phase.values() if len(set(v.values())) == 1)
    if verbose:
        print('ACCEPTANCE — a REGISTRATION, over all %d sheets, every active frame:' % nsheet)
        print('  (1) ON-LATTICE     components %d, off-lattice %d -> %s'
              % (ncomp, nbad, 'PASS' if nbad == 0 else 'FAIL'))
        print('  (2) SEAMLESS       sheet-phases matching the datum %d/%d;'
              % (seam_ok, seam_tot))
        print('                     suit-frames where all 4 slots agree %d/%d -> %s'
              % (agree_slots, len(per_frame_phase),
                 'PASS' if agree_slots == len(per_frame_phase) and seam_ok == seam_tot else 'FAIL'))
        print('  (3) EXTERNAL       components whose OWN origin would give the same phase '
              '%d/%d = %.3f  (chance %.3f, must be < %.2f) -> %s'
              % (ext_hit, ext_tot, ext_hit / max(ext_tot, 1), 1.0 / P, EXT_MAX,
                 'PASS' if ext_hit / max(ext_tot, 1) < EXT_MAX else 'FAIL'))
        print('                     it sits above chance, and that is not a defect: a garment\'s')
        print('                     top edge and the wearer\'s crown are both on the same body,')
        print('                     so the two origins are correlated. The claim is only that the')
        print('                     piece does not DETERMINE the phase — the control does, at 1.0.')
        print('  (4) BODY-TRACKING  residual phases in BODY coords %s (must be {0});'
              % sorted(body_res))
        print('                     distinct phases in SHEET coords %d (must be > 1) -> %s'
              % (len(sheet_phases),
                 'PASS' if body_res == {0} and len(sheet_phases) > 1 else 'FAIL'))
        print('  (5) ONE LATTICE    distinct (A,B,P) %s; oblique (A!=0 and B!=0) %s -> %s'
              % (sorted(lattices), A != 0 and B != 0,
                 'PASS' if len(lattices) == 1 and A != 0 and B != 0 else 'FAIL'))
        for f in firsts:
            print('     VIOLATION %s' % f)
    ok = (nbad == 0 and seam_ok == seam_tot
          and agree_slots == len(per_frame_phase)
          and ext_hit / max(ext_tot, 1) < EXT_MAX and body_res == {0} and len(sheet_phases) > 1
          and len(lattices) == 1 and A != 0 and B != 0)
    if verbose:
        print('OVERALL: %s' % ('ALL PASS' if ok else 'FAIL'))
    return ok


def _lattice_of(mode, slot):
    """The lattice a control is READ on. A control read through this axis's lattice would fail
    everything for the uninteresting reason that the reader cannot see it; each is read on its
    own, so that what it fails is its own fault and not the reader's."""
    if mode == 'per-slot-pitch':
        p = {'chest': 10, 'legs': 8, 'boots': 6, 'helmet': 12}[slot]
        return (A, B, p, tuple(PROFILE[int(round(k * P / float(p)))] for k in range(p)))
    if mode == 'horizontal':
        return (0, B, P, PROFILE)
    return (A, B, P, PROFILE)


def _clauses_for(mode, cls='warrior', gender='m'):
    """SEAMLESS / EXTERNAL / BODY-TRACKING / ONE LATTICE for the axis (mode=None) or a control,
    all measured the same way, on one suit."""
    suffix = '_f' if gender == 'f' else ''
    dt = datum_table(gender)
    stops = DATUMPAL[cls]
    phases, body_res, lattices = {}, set(), set()
    ext_hit = ext_tot = 0
    for slot, cfg in SLOTS.items():
        lat = _lattice_of(mode, slot) if mode else (A, B, P, PROFILE)
        lattices.add(lat[:3])
        base = load_any('%s%s.png' % (cfg['srcs'][cls], suffix))
        arr = build(base, cls, gender, slot, mode=mode, seed=7)
        for fi in range(ACTIVE):
            r, c = fi // COLS, fi % COLS
            sl = (slice(r * FH, (r + 1) * FH), slice(c * FW, (c + 1) * FW))
            a = base[sl][..., 3] > 0
            if not a.any() or fi not in dt:
                continue
            fr = arr[sl]
            lbl, n = label4(a)
            for k in range(1, n + 1):
                m = lbl == k
                if m.sum() < 4:
                    continue
                est, _ = estimate_phase(fr, m, stops, lat)
                ext_tot += 1
                # EXTERNAL is asked per component and compares the phase actually on the pixels
                # with the phase the piece's own bounding box would have chosen. Nothing about
                # the mode is hard-coded here: SELF-ANCHORED comes out at 1.000 because it IS
                # that rule, not because it is named in an if-statement.
                if est == self_phase(m, lat):
                    ext_hit += 1
            est, agree = estimate_phase(fr, a, stops, lat)
            phases.setdefault(fi, {})[slot] = est
            # in BODY coordinates: how far the sheet's phase sits from the wearer's crown, in
            # units of the lattice actually in use. Constant across frames = tracks the body.
            body_res.add((est - (lat[0] * dt[fi][1] + lat[1] * dt[fi][0])) % lat[2])
    disagree = sum(1 for v in phases.values()
                   if len(v) != len(SLOTS) or len(set(v.values())) != 1)
    return dict(disagree=disagree, nframes=len(phases),
                ext=ext_hit / max(ext_tot, 1), body=sorted(body_res),
                lattices=sorted(lattices))


def controls_report():
    """The axis and the five controls, every one measured by the same four clauses."""
    print('== THE AXIS AND THE FIVE CONTROLS, warrior suit, all measured the same way')
    print('   %-15s %-10s %-9s %-22s %s'
          % ('', 'SEAMLESS', 'EXTERNAL', 'BODY-TRACKING', 'ONE LATTICE / OBLIQUE'))
    rows = [(None, 'DATUM (axis)')] + [(m, m) for m in CONTROLS]
    out = {}
    for mode, label in rows:
        r = _clauses_for(mode)
        seam = 'PASS' if r['disagree'] == 0 else 'FAIL %d/%d' % (r['disagree'], r['nframes'])
        ext = ('PASS %.3f' % r['ext']) if r['ext'] < EXT_MAX else ('FAIL %.3f' % r['ext'])
        bod = ('PASS (residual %s)' % r['body']) if len(r['body']) == 1 \
            else ('FAIL (%d residuals)' % len(r['body']))
        lats = r['lattices']
        obl = all(a != 0 and b != 0 for a, b, _ in lats)
        one = ('PASS' if len(lats) == 1 and obl
               else ('FAIL not oblique' if len(lats) == 1 else 'FAIL %d pitches' % len(lats)))
        print('   %-15s %-10s %-9s %-22s %s' % (label, seam, ext, bod, one))
        out[label] = r
    print('   SELF-ANCHORED is the row to read: it is what every prior axis does, it is')
    print('   indistinguishable from this axis on any single sheet, and it disagrees with itself')
    print('   across the four slots in every frame of the suit.')
    print('   HORIZONTAL fails BODY-TRACKING as well as OBLIQUE, and the reason is worth keeping:')
    print('   with A = 0 the lattice coordinate is 2y, so it only ever takes EVEN residues and')
    print('   samples five of its own ten profile positions. Its phase is therefore identifiable')
    print('   only up to +/-1 and the reader picks the lower of the pair, which shows up as two')
    print('   residuals. A level lattice on an integer grid is degenerate — one more argument for')
    print('   OBLIQUE than the one the clause was written for.')
    return True



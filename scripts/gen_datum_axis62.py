#!/usr/bin/env python3
"""SIXTY-SECOND net-new-geometry axis for ALL FOUR SLOTS — the DATUM family: one oblique rib
lattice, laid across the whole suit from an origin that is not on the armour at all but on the
WEARER — the crown of the skull. The cuirass, the chausses, the sabatons and the helm are four
windows onto ONE ornament, so a rib that leaves the bottom of the breastplate arrives at the top of
the thigh, and the same rib arrives at the boot.

    the ornament is  CREST  (the lit top of a rib)
                   + SHADE  (the rib's own cast shadow, immediately below it)
                   + FIELD  (the plate between ribs)
    and its position is  u = A(x - x_datum) + B(y - y_datum)  mod P,  read off the WEARER.

*** THIS IS THE FIRST AXIS WHOSE ORIGIN IS OUTSIDE THE PIECE. ***
Every one of the sixty-one before it is anchored to the component it is drawn on. The 11th flutes
from the plate's own edge, the 46th tiles from the plate's own bounding box, the 47th measures
distance to the plate's own silhouette, the 53rd sizes its beads from the room the plate leaves,
the 57th hangs its swags from the plate's own top, the 60th windows its word at the plate's own
leading edge, and the 61st derives every length it has from the plate's own extent. That is why
every one of them is a property of a SHEET: you can hold one sheet up on its own and the ornament
is complete, and it is also why the seam between two pieces of a suit is, on every one of them, a
discontinuity — two ornaments that happen to be made of the same stuff, meeting.

This one has no sheet-level existence at all. Ask it where a rib goes on a boot and it cannot
answer from the boot. It goes where the wearer's head is. Four sheets that know nothing about each
other come out registered because all four asked the same question of the same body, and the
evidence is a thing no previous axis could even be asked for: DRESS THE CHARACTER AND THE RIBS LINE
UP ACROSS THE SEAMS.

*** THE DATUM, AND WHY IT IS THE SKULL. ***
The origin is the CROWN of the wearer's skull, taken per frame from the skin sheet: the topmost run
of 5 or 6 pixels with nothing above it that widens by one pixel each side on each of the next two
rows — the 5 -> 7 -> 9 skull profile that SPRITE_SPEC already fixes. It is the one landmark on the
body that is a landmark in every pose, it belongs to the wearer rather than to any garment, and it
moves with the animation, which is the whole reason the ribs do not crawl. See THE RENDER-PAID
LESSONS below for why it is emphatically NOT the topmost pixel of the wearer.

*** ACCEPTANCE — A NEW KIND: A REGISTRATION. A CLAIM ABOUT A SHARED FRAME OF REFERENCE. ***
Predecessors are accepted on a statistic (46/48/50/52/53), a topology (54), the algebra of an order
(55), a conservation law on a traversal (56), a physical law (57), a group action (58), a census of
a group (59), the complexity of a formal language (60) and a similarity (61). The 61st is the only
one that needed more than one picture, and what it needed was a RANGE of sizes. This one needs
something stronger and different in kind: several pictures that are not of the same thing, that
were generated by separate runs which never saw one another, and that must nonetheless agree about
where the world is. The test is therefore not run on a component and not run on a sheet. It is run
on a SUIT.

    (1) ON-LATTICE     every painted pixel of every sheet carries the role that
                       u = A(x-xd) + B(y-yd) mod P gives it, with (xd,yd) the wearer's crown for
                       that frame. The umbrella; per component.
    (2) SEAMLESS       the phase estimated INDEPENDENTLY off each of the four slot sheets of a suit
                       — chest, legs, boots, helm — is the same phase, in every frame. Four sheets
                       generated in four separate passes agree to the pixel.
    (3) EXTERNAL       the negative clause, and the one that says this axis is not any of the other
                       sixty-one: the phase is NOT recoverable from the piece. For each component
                       the phase a self-anchored axis would give it is computed, and the two agree
                       on no more of the batch than chance (1 in P) allows.
    (4) BODY-TRACKING  in BODY coordinates the phase residual is zero in all 35 active frames,
                       while in SHEET coordinates the phase takes several distinct values. The
                       lattice is nailed to the wearer, not to the canvas; this is the clause that
                       is the difference between an ornament that rides the walk cycle and one
                       that crawls underneath it.
    (5) ONE LATTICE    over all 24 sheets, every frame and every component, exactly ONE (A,B,P) —
                       and it is OBLIQUE, i.e. neither A nor B is zero, so no rib is a row or a
                       column of the sprite grid.

*** THE FIVE CONTROLS, AND THE FIRST OF THEM IS THE ENTIRE POINT. ***
    SELF-ANCHORED   every component takes its own bounding box as origin — which is not a straw
                    man, it is WHAT ALL SIXTY-ONE PRIOR AXES DO. Passes ON-LATTICE on every sheet
                    taken alone; a single sheet of it is INDISTINGUISHABLE from this axis by eye
                    and by any test that looks at one sheet. It fails SEAMLESS and it fails
                    EXTERNAL. You cannot tell the control from the axis until you dress the
                    character, and that is the sharpest statement of what the axis is for.
    FRAME-ANCHORED  origin at the sprite frame's own (0,0): the sheets do register with each other,
                    so it PASSES SEAMLESS, and it fails BODY-TRACKING. Its visible defect is the
                    classic one — the ribs stand still while the character walks through them.
                    It is the honest reason the datum is a body landmark and not the canvas corner,
                    and it is the reason clause 4 exists at all.
    PER-SLOT-PITCH  each slot picks the pitch that best fits its own geometry, i.e. the adaptive
                    boundary rule that NINE earlier axes carry as their hard-won lesson and that
                    the 61st makes compulsory. Here it is fatal: it fails ONE LATTICE, because two
                    pitches cannot cross a seam. The 61st and this one make opposite demands and
                    both are right about their own claim.
    HORIZONTAL      A = 0: level bands, still perfectly registered to the datum. Passes 1-4 and
                    fails the OBLIQUE half of clause 5 — a horizontal band registered to the body
                    is the 12th axis's BANDED LAMELLAR with extra steps, because a level line
                    crossing a seam is not evidence of anything: it would line up by accident.
                    THIS CONTROL IS WHY THE RIBS ARE OBLIQUE. Only a slanted line crossing a seam
                    can only line up on purpose.
    RANDOM-PHASE    a phase drawn per piece. Fails 1-4. The upper collapse boundary: registration
                    without a rule is the 46th CRAQUELURE with a slant.

*** THE PRICE, AND IT IS THE EXACT REVERSE OF THE 61st, AGAIN DELIBERATELY. ***
The 61st CANON fits the ornament to the piece so completely that it has no size of its own; this
one refuses to look at the piece at all. So the piece has NO SAY: a sabaton may catch a crest, or
catch only shade, or in the shortest poses catch neither, and nothing is done about it, because
doing something about it is exactly the SELF-ANCHORED control. A second cost, and it is the first
time in sixty-two axes that the deliverable itself changes: THE ORNAMENT CANNOT BE JUDGED ON A
SINGLE SHEET. A chest of this axis, alone, looks like slanted ribs placed nowhere in particular —
which is precisely what it is, alone. Hence the preview panels for this axis are composites of a
DRESSED character, and `_ZOOM_datum_suit.png` is the axis's real evidence.

*** DISTINCTNESS. ***
  * 11th FLUTING / 43rd GADROON / 42nd STRIGIL — parallel ribs, but vertical, at a pitch measured
    from the piece. Rotate them and anchor them to the piece and you have the SELF-ANCHORED
    control; that is the family this axis is defined against.
  * 12th BANDED LAMELLAR / 55th STRATA — level bands. That is the HORIZONTAL control.
  * 16th TWILL / 25th ARGYLE / 44th ZIGZAG — oblique, but as a repeating cell tiled from the
    piece's own box, and reversing direction. One family of straight parallel ribs that never turns
    is the plainest linear ornament in the set, and it is plain ON PURPOSE: a registration can only
    be seen if the thing being registered is simple enough that the eye can follow one rib across a
    seam. An ornate motif would hide the only claim this axis makes.
  * 61st CANON — the exact complement. Everything from the piece's own extent vs nothing from it.
  * 57th FESTOON — "the first axis that has an UP", i.e. the first to consult the world for a
    DIRECTION. This one consults the world for an ORIGIN, which is strictly more: a direction is
    shared by every piece for free, a position is not.

Geometry:
    lattice   u(x,y) = A*(x - xd) + B*(y - yd)  with (A,B) = (-1, 2), P = 10
              the normal leans LEFT because the character faces left (CONTEXT: 3/4 perspective).
              pitch = P / sqrt(A^2+B^2) = 10/sqrt5 = 4.47 px between rib crests.
    profile   u mod P -> CREST CREST SHADE SHADE FIELD FIELD FIELD FIELD FIELD FIELD
              crest over its own shadow, immediately, with no field row between: at this pitch a
              gap between the lit row and the dark one reads as two thin lines instead of one
              rib with a top. Chosen by rendering five profiles at three pitches through
              finish_array (`--profiles`), not by argument.
    datum     the wearer's skull crown, per gender and per frame, from the skin sheet.

*** NO COMPONENT LABELLING ANYWHERE IN THE GENERATOR, AND THAT IS A PROPERTY, NOT AN OMISSION. ***
Every prior axis begins by segmenting the sheet, because every prior ornament has to know what
piece it is on. This one paints from a global field: a pixel is told its role by its own coordinates
and the wearer's crown, and it does not need to know which garment it belongs to, or whether the
garment has one part or five. `label4` appears in this file only inside the acceptance test and the
diagnostics.

Authoring philosophy identical to gen_canon_axis61.py / gen_cadence_axis60.py: every pattern pixel
is painted ONLY onto pixels ALREADY opaque in the body. Nothing added, nothing removed, silhouette
untouched — QA-safe by construction. Sleep frames (fi >= 60) get a plain recolor.

FINISHING PASS: this generator does NOT shade for itself. Every sheet goes through
`sprite_finish.finish_array(arr, dst)` and is written with `save_finished()`. See CONTEXT.md
"MANDATORY - the finishing pass". Eighteenth generator to call it in-line, after axes 45-61.

Run from repo root:
  python3 scripts/gen_datum_axis62.py
  python3 scripts/gen_datum_axis62.py --lattice    # the lattice, the profile, the datum table
  python3 scripts/gen_datum_axis62.py --cells      # ASCII of real components + the clauses
  python3 scripts/gen_datum_axis62.py --accept     # the clauses over all 24 sheets and every frame
  python3 scripts/gen_datum_axis62.py --profiles   # the profile/pitch A-B that chose the rib
  python3 scripts/gen_datum_axis62.py --sweep      # dressed suits: the axis and the five controls
Then QA (examples):
  python3 scripts/sprite_qa.py _datum_legendary_preview/shirt_warrior_legendary62.png
  python3 scripts/sprite_qa.py _datumdome_helmet_preview/helmet_mage_legendary62.png --y-min 2
  python3 scripts/sprite_qa.py _datum_boots_preview/boots_warrior_legendary_datum.png --y-max 63
"""

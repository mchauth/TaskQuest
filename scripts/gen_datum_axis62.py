def _big_comp(arr, fi=0):
    r, c = fi // COLS, fi % COLS
    src = arr[r * FH:(r + 1) * FH, c * FW:(c + 1) * FW]
    a = src[..., 3] > 0
    lbl, n = label4(a)
    counts = np.bincount(lbl.ravel())
    counts[0] = 0
    return (lbl == int(counts.argmax())) if n else a


def dump_cells():
    """ASCII of real components under the axis, with the clauses stated on each."""
    legend = {R_CREST: '^', R_SHADE: 'v', R_FIELD: '-'}
    dt = datum_table('m')
    ph = phase_of(dt[0])
    stops = DATUMPAL['warrior']
    allpass = True
    for label, fname in (('warrior chest', 'armor_chest_4.png'),
                         ('warrior legs', 'armor_pants_4.png'),
                         ('warrior boot', 'armor_boots_4.png'),
                         ('warrior helm', 'helmet_rare1.png')):
        comp = _big_comp(load_any(fname))
        fr = np.zeros(comp.shape + (4,), dtype=np.uint8)
        paint(fr, comp, stops, ph)
        ys, xs = np.nonzero(comp)
        y0, y1, x0, x1 = ys.min(), ys.max(), xs.min(), xs.max()
        est, agree = estimate_phase(fr, comp, stops)
        sph = self_phase(comp)
        print('== %s   frame 0, crown at (y=%d, x=%d), datum phase %d'
              % (label, dt[0][0], dt[0][1], ph))
        ys2, xs2, role = read_roles(fr, comp, stops)
        rmap = np.full(comp.shape, -1, np.int8)
        rmap[ys2, xs2] = role
        for y in range(y0, y1 + 1):
            print('   ' + ''.join(legend[int(rmap[y, x])] if comp[y, x] else ' '
                                  for x in range(x0, x1 + 1)))
        ok = (est == ph and agree > 0.999)
        print('   phase read back off the pixels: %d (%.3f agreement) -> %s'
              % (est, agree, 'ON-LATTICE' if ok else 'FAIL'))
        print('   the phase this piece would have chosen for itself: %d  %s'
              % (sph, '(differs — EXTERNAL)' if sph != ph else '(coincides — 1 chance in %d)' % P))
        allpass = allpass and ok
    print()
    print('legend: ^ crest   v shade   - field')
    print('OVERALL: %s' % ('ALL PASS' if allpass else 'FAIL'))
    return allpass



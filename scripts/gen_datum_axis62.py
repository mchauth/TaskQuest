def dress(cls, gender='m', frames=(0,), mode=None, finish=True):
    """Composite a DRESSED character — the only view in which this axis says anything."""
    suffix = '_f' if gender == 'f' else ''
    sheets = {}
    for slot in ('legs', 'boots', 'chest', 'helmet'):
        base = load_any('%s%s.png' % (SUIT_SRC[cls][slot], suffix))
        arr = build(base, cls, gender, slot, mode=mode, seed=7)
        if finish:
            arr, _ = finish_array(arr, '%s/%s%s.png'
                                  % (SLOTS[slot]['outdir'], SLOTS[slot]['dst'] % cls, suffix))
        sheets[slot] = arr
    outs = []
    for fi in frames:
        r, c = fi // COLS, fi % COLS
        comp = np.zeros((FH, FW, 4), np.uint8)
        for slot in ('legs', 'boots', 'chest', 'helmet'):
            cell = sheets[slot][r * FH:(r + 1) * FH, c * FW:(c + 1) * FW]
            m = cell[..., 3] > 0
            comp[m] = cell[m]
        outs.append(comp)
    return outs


def sweep(path='_diag_datum_sweep.png', zoom=12):
    """THE AXIS AND THE FIVE CONTROLS, on a dressed character. SELF-ANCHORED is the cell to stare
    at: on any single sheet it is this axis; here the ribs step at every seam."""
    modes = [None] + list(CONTROLS)
    crop = (slice(14, 63), slice(26, 58))
    h = (crop[0].stop - crop[0].start) * zoom
    w = (crop[1].stop - crop[1].start) * zoom
    pad = 8
    img = Image.new('RGBA', (pad + len(modes) * (w + pad), pad + 3 * (h + pad)), (24, 24, 28, 255))
    for i, cls in enumerate(('warrior', 'mage', 'ranger')):
        for j, m in enumerate(modes):
            c = dress(cls, 'm', (0,), mode=m)[0]
            im = Image.fromarray(c[crop]).resize((w, h), Image.NEAREST)
            img.paste(im, (pad + j * (w + pad), pad + i * (h + pad)))
    img.save(path)
    print('wrote %s   columns: DATUM, %s' % (path, ', '.join(CONTROLS)))



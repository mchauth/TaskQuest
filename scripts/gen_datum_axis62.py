# --- THE LATTICE ------------------------------------------------------------------------------
# (A, B) is the normal of the rib family. It leans LEFT because the character faces left. B = 2A
# in magnitude gives a rib that drops one pixel every two columns, which is the shallowest slant
# that is unambiguously not a row of the sprite grid and still legible at 13px.
A, B = -1, 2
P = 10                           # period, in lattice units; pitch = P / sqrt(5) = 4.47 px

R_CREST, R_SHADE, R_FIELD = 0, 1, 2
ROLENAME = {R_CREST: 'CREST', R_SHADE: 'SHADE', R_FIELD: 'FIELD'}
# crest immediately over its own shadow — see --profiles
PROFILE = (R_CREST, R_CREST, R_SHADE, R_SHADE,
           R_FIELD, R_FIELD, R_FIELD, R_FIELD, R_FIELD, R_FIELD)
assert len(PROFILE) == P

# The skull, from SPRITE_SPEC: the crown is a run of 5 (male) or 6 (female, in the cheer pose)
# that widens by one pixel each side on each of the next two rows. Written as the profile it is
# rather than as a width, because a width is exactly what the cheer row makes untrustworthy.
CROWN_W = (5, 6)
SKIN = {'m': 'skin_m1.png', 'f': 'skin_f1.png'}      # silhouette is identical across skin tones

# --- palette ----------------------------------------------------------------------------------

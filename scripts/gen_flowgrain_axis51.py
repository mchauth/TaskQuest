#!/usr/bin/env python3
"""FIFTY-FIRST net-new-geometry axis for ALL FOUR SLOTS — the FLOWGRAIN family (a continuous
DIRECTOR FIELD with topological defects): the surface is figured with one unbroken family of raised
ridges whose DIRECTION IS A SMOOTH FUNCTION OF POSITION — the grain sweeps across the plate, wraps
around a KNOT where the ridges close on themselves, and splits at a DELTA where two streams of grain
part company. It is the figure in a burl, the water in a pattern-welded blade around a punched eye,
the flow in a fingerprint.

    the ornament is  RIDGE  (a raised convex member, lit crest -> flank -> groove across its width)
                   + FIELD  (the ridge's DIRECTION at a point, which is different at every point)
                   + DEFECT (the two singular points the whole field is organised around:
                             a KNOT/core where ridges close, a DELTA where they bifurcate)

*** THIS IS THE FIRST CONTINUOUS-FIELD AXIS, AND THE FIRST AXIS WITH NO REPEATING MEMBER. ***
Every one of the fifty prior axes is generated by a UNIT. Forty of them stamp a congruent cell on a
lattice (hexagon, scale, arch, coffer, bay); ten run a congruent member along a track (flute, wave,
meander, cable, guilloche, strigil, gadroon, zigzag); the three most recent break the unit's
*content* — 48th cosmati gives it a hierarchy of sizes, 49th dendrite gives it descent, 50th runic
gives it a vocabulary — but all three still lay their content into a ruled, periodic carrier, and in
all fifty you can point at the thing that repeats. Here you cannot. Tone is an ANALYTIC FUNCTION of
position, `t = frac(PHI(x, y) / 2*pi)`, and no two ridges on the plate are congruent: they have
different lengths, different curvatures, different orientations, and some of them close into loops
while others run off the silhouette. The axis is not a pattern that has been placed on the armour,
it is a FIELD that the armour has been cut out of, and the structure that makes it read as ornament
rather than as noise is not a grid — it is the field's SINGULARITIES.

The families it could be confused with, and why each fails:
  * The line axes — 11th fluting, 42nd strigil, 43rd gadroon, 44th zigzag, 22nd wave, 30th cable —
    all have a GLOBAL DIRECTION. A flute is vertical everywhere on the piece; a strigil S-curve is
    the same S at every column; a wave is the same sine translated. Rotate the piece and you can
    still name the one direction the family runs. Here there is no such direction: the grain runs
    -28 deg at the hem, turns through the vertical at the knot, and comes back the other way past
    the delta. Direction is a LOCAL property, which is the whole subject.
  * The 47th mokume is the sharpest near miss, because it is also unruled and its bands also curve.
    But mokume's bands are CONTOURS OF THE SILHOUETTE — tone is f(distance-to-edge), so the figure
    is a property of the OUTLINE and every band is a scaled copy of the boundary, closed and nested.
    Flowgrain's ridges are contours of a field that knows nothing about the outline; they are open,
    they are not nested, they cross the silhouette at every angle, and the piece can be reshaped
    without changing the grain. Nesting is containment; this is flow.
  * The 24th spiral and 28th concentric close their curves around TILED CENTRES — a periodic
    lattice of cores, each core's neighbourhood a copy of the last. This axis has TWO singular
    points on the whole piece, of TWO DIFFERENT KINDS (a +1/2 core and a -1/2 delta), and away from
    them the field is not organised around anything.
  * The 46th craquelure is the other axis with no repeating unit, and the relation is worth stating
    because it is the exact opposite failure of periodicity. Craquelure is DISORDER without
    periodicity: a jittered partition, C-nothing continuous, no straight line anywhere, every
    junction an accident of a PRNG. Flowgrain is SMOOTH ORDER without periodicity: one differentiable
    function, no randomness at all, every ridge exactly parallel to its neighbour everywhere, and
    the only two places anything happens are dictated by topology, not by chance. One is noise, the
    other is a flow; they cannot be mistaken for one another at 1x.

RELIEF, and the second thing that is new here. Every prior axis picks its stop from WHERE a pixel
sits in the cell. This one picks the crest stop from WHICH WAY THE RIDGE IS POINTING: a crest whose
ridge runs across the light (the light is upper-left, as everywhere in the set) takes the bright
nickel stop, a crest whose ridge runs along the light takes the dull one, and because direction
varies continuously the highlight MIGRATES along the grain — the shimmer that makes real figured
material look wet. That is orientation-dependent shading, and it is only possible on an axis whose
subject is orientation.

Geometry. The phase is the classic director field with point defects,

    PHI(x, y) = (2*pi / PITCH) * (x*cos(ALPHA) + y*sin(ALPHA))          the carrier
                + SUM_i  q_i * w(r_i) * atan2(y - dy_i, x - dx_i)      the defects

with charges q = +2 (the KNOT) and q = -2 (the DELTA): walk a circle around one and the phase gains
two whole periods, so two extra ridges are inserted there and every ridge nearby has to bend to make
room. The charges sum to zero, so far from the pair the grain is undisturbed and the piece keeps a
prevailing sweep. Both defects are placed in COMPONENT-LOCAL fractions, with the knot LEFT of centre
and high, per the standing rule that the character faces LEFT.

Two terms there are not cosmetic, and each is tuned against a specific failure:

  * q MUST BE AN INTEGER. atan2 jumps by 2*pi across its branch cut, so the phase jumps by q * 2*pi
    along a ray out of each core, and the banding frac(PHI / 2*pi) only hides that jump when q is a
    whole number of periods. The honest half-charge of a real fingerprint delta (q = 1/2) leaves half
    a period of mismatch along a straight line right across the piece — and a straight discontinuity
    is the one thing a flow must not have. It reads as a scratch, or worse as a plate seam, and the
    armour looks like two pieces butted together.
  * w(r) = r^2 / (r^2 + CORE_R^2) rolls each defect off inside CORE_R. An undamped atan2 has
    unbounded gradient at its centre, so ridge spacing collapses to nothing there and the knot comes
    out as a 3px smear of alternating pixels — the mush the 30th cable was retuned to avoid. Damping
    trades topological purity for a core whose ridges stay a pixel apart: on a 13x20 torso
    |grad PHI| p95/median falls from 2.53 to 1.39, i.e. from "much of the field is compressed" to
    "nowhere is the spacing more than a third tighter than the carrier's". A real ridge core is a
    tight curve rather than a singularity, so this is also the truer picture.

Authoring philosophy identical to gen_runic_axis50.py / gen_dendrite_axis49.py: every pattern pixel
is painted ONLY onto pixels ALREADY opaque in the body, so the generator CANNOT create isolated
pixels, background bleed or extra components — QA-safe by construction. Sleep frames (fi >= 60) get
a plain body recolor.

FINISHING PASS: this generator does NOT shade for itself. Every sheet goes through
`sprite_finish.finish_array(arr, dst)` and is written with `save_finished()` — the canonical chain
(no-smooth shading with protect=False, shirt pauldron/gorget/chest-plate separation, helmet black
eye+mouth visor with NO full-silhouette rim, hat brim/crease folds for open headgear). See
CONTEXT.md "MANDATORY - the finishing pass".

Run from repo root:
  python3 scripts/gen_flowgrain_axis51.py
  python3 scripts/gen_flowgrain_axis51.py --field     # ASCII dump of the field + gradient stats
  python3 scripts/gen_flowgrain_axis51.py --swatch    # bare motif on a test plate, no sheets
  python3 scripts/gen_flowgrain_axis51.py --sweep     # PITCH sweep on a real torso AND a real leg
Then QA (examples):
  python3 scripts/sprite_qa.py _flowgrain_legendary_preview/shirt_warrior_legendary51.png
  python3 scripts/sprite_qa.py _flowgraindome_helmet_preview/helmet_mage_legendary51.png --y-min 2
  python3 scripts/sprite_qa.py _flowgrain_boots_preview/boots_warrior_legendary_flowgrain.png --y-max 63
"""

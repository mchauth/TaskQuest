# --- Flowgrain constants --------------------------------------------------------------------
# PITCH is the ridge period in pixels of the UNDISTURBED carrier (near the defects the field
# stretches and compresses it, which is the point). Swept 5.5/4.5/4.0/3.6/3.0 (--sweep) on a real
# torso AND a real leg. Like the 49th and 50th this axis is bounded on both sides by a collapse into
# an OLDER axis rather than into mush, but here the two ends are DIFFERENT axes:
#   5.5  a 13px torso carries 3 ridges and a thigh 2. Three curved bands on a plate is the 47th
#        MOKUME — at that count the eye reads them as contours of the silhouette, because there are
#        too few of them to establish that they are contours of anything else. The flow dies for
#        want of members and the knot has no room to close.
#   4.5  4 ridges on the torso; the knot closes but only just, and the delta falls off the hip.
#   4.0  5 ridges, both defects legible on the chest, still one clear ridge either side of the knot.
#   3.6  6 ridges on the torso and 4 down a thigh, the knot closing inside 5px, the delta split
#        visible, crest-flank-groove still a clean 3-stop profile across each member — chosen.
#   3.0  the profile loses its flank: crest and groove sit adjacent, so each ridge is a 1px light /
#        1px dark pair and the convex relief is gone. What is left is a fine two-tone hatch whose
#        local direction the eye cannot resolve at 1x, and a hatch that dense reads as the 16th
#        TWILL with a wobble — direction, the entire subject, becomes unreadable exactly when there
#        is most of it on the plate.
PITCH = 3.6
# ALPHA is the direction of the phase GRADIENT, so the undisturbed ridges run perpendicular to it.
# 62 deg puts the prevailing grain at about -28 deg from the horizontal, deliberately off every
# family axis in the set: horizontal grain reads as the 47th mokume or a banded lamellar, vertical
# as the 11th fluting or 43rd gadroon, 45 deg as the 16th twill. The defect pair then swings the
# local direction through roughly +/-90 deg of that, so no one direction owns the plate.
ALPHA = np.deg2rad(62.0)
# Defects as (charge, x, y), the position in fractions of the component bounding box. The KNOT is
# left of centre and high — the character faces LEFT, so the organising feature of the field belongs
# on the lit side. The DELTA sits below and right of it, a TIGHT pair: swept both, and a pair spread
# to opposite corners (0.36,0.32)/(0.68,0.70) rotates the grain through 90 deg over the whole middle
# of the plate, which lands a broad horizontal band across the chest and reads as the 8th SIDE-STRIPE
# with texture in it. Bringing the two cores within about 7px keeps the disturbance local: the knot
# closes, the delta splits, and the rest of the piece keeps its prevailing sweep, which is what makes
# the two singular points read as FEATURES of a flow instead of as a seam between two textures.
#
# THE CHARGE MUST BE AN INTEGER, and that is the one hard constraint in the whole axis. The defect
# term is `q * atan2(...)`, and atan2 jumps by 2*pi across its branch cut, so the phase jumps by
# q * 2*pi along a ray running out from each core. Banding takes `frac(PHI / 2*pi)`, so an INTEGER q
# makes that jump land on a whole number of periods and vanish — the ridges cross the cut without a
# join. A fractional charge (q = 0.5, the honest half-charge of a real fingerprint delta) leaves half
# a period of mismatch along a straight line right across the piece, and a straight discontinuity is
# the one thing a flow must not have: it reads as a scratch, or worse as a plate seam, and the field
# looks like two pieces of armour butted together. Swept 1 / 2 / 3: at 1 the grain barely bends on a
# 13px torso and the axis is a diagonal 11th fluting; at 2 the knot closes inside 5px with a clear
# ridge either side and the delta's split is legible; at 3 the spacing at the cores compresses past
# 1px and both cores turn into a smear.
KNOT = (+2.0, 0.32, 0.30)
DELTA = (-2.0, 0.62, 0.52)
CORE_R = 3.0       # damping radius; below this the defect term is rolled off — see docstring
# Ridge profile across one period. Convex member: a lit crest, a mid flank falling away from it, a
# groove at the bottom of the cut. Boundaries chosen so at PITCH 3.6 each stop lands on about one
# pixel; the crest gets the largest share because it is the only stop that carries direction.
T_CREST, T_FLANK, T_GROOVE = 0.30, 0.58, 0.82
# How square-on to the light a ridge must run before its crest takes the bright stop. The threshold
# is on |ridge normal . light|, and the geometry is not symmetric the way it looks: with the light
# up-left, a ridge at 45 deg PARALLEL to it ('\') is the only orientation that goes fully dull, while
# horizontal, vertical and '/' ridges all sit at 0.71 or above. So a threshold under about 0.8 lights
# most of the plate, the lift stops being a highlight, and on a 13px torso the strip where the field
# turns horizontal comes out as one hard white bar across the chest — a bar reads as a BELT (the 8th
# side-stripe) and swamps the grain under it. At 0.86 only the crests within about 10 deg of square-on
# lift, the shimmer is a minority of the crest, and it MIGRATES as the direction turns, which is the
# whole point of an orientation-shaded axis.
FACE_T = 0.86

# Per class, five stops: crest lit across the light / crest lit along it / flank / groove / deep.
#   * No stop is near pure black. This is a HELMET constraint, not taste: the finishing pass carves
#     the visor as black eye and mouth pixels and a near-black groove swallows the face slit (the
#     lesson the 49th paid for on its first cut).
#   * Every pale stop is clear of the skin ramp. On a narrow female chest the crests are most of
#     what is visible and a warm off-white would read as bare shoulder at 1x (the 47th's rose gold).
#   * The two crest stops are deliberately CLOSE together. The first cut ran them 236 against 170,
#     and because the orientation term switches between them on a threshold, every stretch of grain
#     that happened to face the light came out as a hard white bar — the highlight stopped reading as
#     a highlight and started reading as a second, brighter pattern laid over the first. A migrating
#     highlight has to be a shimmer, not an element.

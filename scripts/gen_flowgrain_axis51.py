def phase_field(h, w, pitch=None):
    """PHI over an h x w box, in radians, one period per ridge.

    The carrier is a plane wave; each defect adds `q * w(r) * atan2(dy, dx)`, a half-turn of phase
    per circuit, which is a ridge ending (the delta) or a ridge closing on itself (the knot). The
    `w(r)` roll-off is what keeps ridge spacing finite at the cores — see the module docstring."""
    p = PITCH if pitch is None else pitch
    yy, xx = np.mgrid[0:h, 0:w].astype(np.float64)
    phi = (TAU / p) * (xx * np.cos(ALPHA) + yy * np.sin(ALPHA))
    for q, fx, fy in (KNOT, DELTA):
        dx, dy = fx * max(w - 1, 1), fy * max(h - 1, 1)
        ex, ey = xx - dx, yy - dy
        r2 = ex * ex + ey * ey
        phi = phi + q * (r2 / (r2 + CORE_R * CORE_R)) * np.arctan2(ey, ex)
    return phi


def paint_flowgrain(fr, comp, grain, pitch=None):
    """Paint the grain onto one component. Only opaque body pixels are ever painted, so this cannot
    create strays.

    Two things happen per pixel: the position within the ridge period picks the stop, and — for
    crest pixels only — the RIDGE'S LOCAL DIRECTION picks between the two crest stops. The light is
    upper-left throughout the set, so a ridge running across the light catches it and one running
    along it does not, and because the direction turns continuously the highlight travels along the
    grain instead of sitting in a fixed place."""
    if comp.sum() < MIN_PX:
        return
    ys, xs = np.nonzero(comp)
    y0, x0 = int(ys.min()), int(xs.min())
    h = int(ys.max()) - y0 + 1
    w = int(xs.max()) - x0 + 1
    phi = phase_field(h, w, pitch)
    t = np.mod(phi / TAU, 1.0)
    gy, gx = np.gradient(phi)
    # the ridge runs perpendicular to the gradient; how much it faces the upper-left light is
    # |sin| of the angle between the ridge and the light direction, i.e. the normalised component
    # of the gradient along the light.
    # light comes from the UPPER LEFT, and image y grows DOWNWARD, so the light direction is
    # (-1, -1)/sqrt(2) — not 135 degrees read off a maths-convention protractor, which points
    # down-left and highlights exactly the wrong family of ridges.
    gmag = np.hypot(gx, gy) + 1e-6
    lx_, ly_ = -0.70710678, -0.70710678
    face = np.abs((gx * lx_ + gy * ly_) / gmag)

    crest_hi, crest_lo, flank, groove, deep = grain
    left = np.zeros_like(comp)
    right = np.zeros_like(comp)
    up = np.zeros_like(comp)
    left[:, 1:] = comp[:, :-1]
    right[:, :-1] = comp[:, 1:]
    up[1:, :] = comp[:-1, :]
    thin_m = comp & ~(left & right)
    edge_m = comp & ~up

    for y, x in zip(ys, xs):
        ly, lx = int(y) - y0, int(x) - x0
        tv = t[ly, lx]
        if tv < T_CREST:
            # the standing edge rule: the brightest stop never lands on a silhouette edge or on a
            # 1px protrusion, or the piece grows a detached bright rim (the 47th / 49th lesson).
            if edge_m[y, x] or thin_m[y, x]:
                rgb = crest_lo
            else:
                rgb = crest_hi if face[ly, lx] > FACE_T else crest_lo
        elif tv < T_FLANK:
            rgb = flank
        elif tv < T_GROOVE:
            rgb = groove
        else:
            rgb = deep
        fr[y, x, :3] = rgb
        fr[y, x, 3] = 255


def label4(mask):
    """Self-contained 4-connectivity connected-component labelling (scipy-free).
    Returns (labels int32 array, n). Background (False) is label 0."""
    h, w = mask.shape
    labels = np.zeros((h, w), dtype=np.int32)
    n = 0
    stack = []
    for sy in range(h):
        for sx in range(w):
            if mask[sy, sx] and labels[sy, sx] == 0:
                n += 1
                labels[sy, sx] = n
                stack.append((sy, sx))
                while stack:
                    y, x = stack.pop()
                    if y > 0 and mask[y - 1, x] and labels[y - 1, x] == 0:
                        labels[y - 1, x] = n
                        stack.append((y - 1, x))
                    if y < h - 1 and mask[y + 1, x] and labels[y + 1, x] == 0:
                        labels[y + 1, x] = n
                        stack.append((y + 1, x))
                    if x > 0 and mask[y, x - 1] and labels[y, x - 1] == 0:
                        labels[y, x - 1] = n
                        stack.append((y, x - 1))
                    if x < w - 1 and mask[y, x + 1] and labels[y, x + 1] == 0:
                        labels[y, x + 1] = n
                        stack.append((y, x + 1))
    return labels, n


def load_any(fname):
    """Load a source sheet; if the female (_f) variant is absent (warrior boots are a
    single gender-shared sheet), fall back to the base sheet."""
    if os.path.exists(os.path.join(CHAR, fname)):
        return load(fname)
    if fname.endswith('_f.png'):
        return load(fname[:-6] + '.png')
    raise FileNotFoundError(fname)


def put(fr, y, x, rgb):
    if 0 <= y < FH and 0 <= x < FW:
        fr[y, x, :3] = rgb
        fr[y, x, 3] = 255


def recolor(src, fr, a, D, M, L):
    v = src[..., :3].astype(np.float32).max(-1) / 255.0
    vref = float(np.median(v[a]))
    ratio = v / max(vref, 1e-3)
    for y, x in np.argwhere(a):
        q = ratio[y, x]
        tone = D if q < Q_LO else (L if q > Q_HI else M)
        put(fr, y, x, tone)


def build(base, cfg, cls):
    D, M, L = BODY[cls]
    grain = GRAIN[cls]
    largest = cfg['largest']
    out = np.zeros_like(base)
    for fi in range(NFR):
        r, c = fi // COLS, fi % COLS
        sl = (slice(r * FH, (r + 1) * FH), slice(c * FW, (c + 1) * FW))
        src = base[sl]
        a = src[..., 3] > 0
        if not a.any():
            continue
        fr = out[sl]
        recolor(src, fr, a, D, M, L)
        if fi >= 60:                            # sleep: body only
            continue
        if largest:
            lbl, n = label4(a)
            if n >= 1:
                counts = np.bincount(lbl.ravel())
                counts[0] = 0
                comp = (lbl == int(counts.argmax()))
            else:
                comp = a
        else:
            comp = a
        paint_flowgrain(fr, comp, grain)
        # connectivity guard (no-op by construction: only body pixels repainted)
        da = fr[..., 3] > 0
        lbl2, _ = label4(da)
        keep_labels = set(np.unique(lbl2[a])) - {0}
        keep = np.isin(lbl2, list(keep_labels)) if keep_labels else da
        for y, x in np.argwhere(da & ~keep):
            fr[y, x, :] = 0
    return out


# --- diagnostics ----------------------------------------------------------------------------
def _test_plate(w=44, h=30):
    """A synthetic armour-ish plate: a rounded slab with a neck notch and a waist pinch, so the
    grain can be judged on a shape that has the features real slots have."""
    m = np.zeros((h, w), dtype=bool)
    yy, xx = np.mgrid[0:h, 0:w]
    cx = w / 2.0
    for y in range(h):
        ty = y / (h - 1.0)
        hw = 8.5 - 4.0 * abs(ty - 0.55) - 2.5 * max(0.0, 0.18 - ty) * 6.0
        hw = max(hw, 1.5)
        m[y, :] = np.abs(xx[y, :] - cx) <= hw
    m[0:3, int(cx) - 2:int(cx) + 3] = False          # neck notch
    return m


def swatch(path='_diag_flowgrain_swatch.png', zoom=12):
    """Render the bare motif on the test plate for all three classes, so the sweep of the grain, the
    knot and the delta can be judged before any sheet is written."""
    m = _test_plate()
    h, w = m.shape
    pad = 3
    tw, th = w * zoom, h * zoom
    img = Image.new('RGBA', (tw * 3 + pad * 4, th + pad * 2), (24, 24, 28, 255))
    for k, cls in enumerate(('warrior', 'mage', 'ranger')):
        a = np.zeros((h, w, 4), dtype=np.uint8)
        paint_flowgrain(a, m, GRAIN[cls])
        t = Image.fromarray(a).resize((tw, th), Image.NEAREST)
        img.paste(t, (pad + k * (tw + pad), pad))
    img.save(path)
    print('wrote %s (motif only - no sheets written)' % path)


def sweep(path='_diag_flowgrain_sweep.png', zoom=11):
    """Render the warrior chest idle frame at a range of ridge pitches, plus a leg frame, so the
    pitch can be judged on a real piece: at the coarse end on whether enough members survive for
    the flow to read as a flow, and at the fine end on whether the crest-flank-groove profile
    survives at all."""
    base = load_any('armor_chest_4.png')
    legs = load_any('armor_pants_4.png')
    cells = []
    for p in (5.5, 4.5, 4.0, 3.6, 3.0):
        col = []
        for arr, crop in ((base, (26, 20, 54, 46)), (legs, (26, 36, 54, 62))):
            src = arr[0:FH, 0:FW]
            a = src[..., 3] > 0
            lbl, n = label4(a)
            counts = np.bincount(lbl.ravel())
            counts[0] = 0
            comp = (lbl == int(counts.argmax())) if n else a
            fr = np.zeros_like(src)
            paint_flowgrain(fr, comp, GRAIN['warrior'], pitch=p)
            col.append(Image.fromarray(fr).crop(crop))
        cells.append(('PITCH=%.1f' % p, col))
    cw, ch = 28 * zoom, 26 * zoom
    pad, lab = 8, 18
    img = Image.new('RGBA', (pad + len(cells) * (cw + pad), pad * 2 + 2 * (ch + lab)), (24, 24, 28, 255))
    from PIL import ImageDraw, ImageFont
    d = ImageDraw.Draw(img)
    try:
        f = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 13)
    except Exception:
        f = ImageFont.load_default()
    x = pad
    for name, col in cells:
        y = pad
        for im in col:
            img.alpha_composite(im.resize((cw, ch), Image.NEAREST), (x, y))
            d.text((x + 2, y + ch), name, font=f, fill=(210, 210, 220, 255))
            y += ch + lab
        x += cw + pad
    img.convert('RGB').save(path)
    print('wrote %s (pitch sweep - no sheets written)' % path)


def dump_field():
    """ASCII dump of the field on a torso-sized box plus the gradient statistics.

    The stats are the actual acceptance test for this axis. `p95 / median` of |grad PHI| is the
    worst-case ridge-spacing compression: at 1.0 the grain is perfectly even (and there is no
    field), and much above 2 the defect cores compress the spacing below a pixel and turn into the
    alternating mush that killed the 30th cable's first cut. CORE_R is set from this number."""
    for label, (hh, ww) in (('torso 13x20', (20, 13)), ('plate 30x44', (30, 44))):
        phi = phase_field(hh, ww)
        gy, gx = np.gradient(phi)
        g = np.hypot(gx, gy)
        t = np.mod(phi / TAU, 1.0)
        ch = np.where(t < T_CREST, '#', np.where(t < T_FLANK, '+', np.where(t < T_GROOVE, '-', '.')))
        print('== %s   PITCH=%.1f ALPHA=%.0fdeg CORE_R=%.1f' % (label, PITCH, np.rad2deg(ALPHA), CORE_R))
        print('   |grad| median=%.2f p95=%.2f  ratio=%.2f  (carrier=%.2f)'
              % (np.median(g), np.percentile(g, 95), np.percentile(g, 95) / np.median(g), TAU / PITCH))
        for y in range(hh):
            print('   ' + ''.join(ch[y]))
    # the two defects, as fractions and as pixels on a 13x20 torso
    for nm, (q, fx, fy) in (('KNOT ', KNOT), ('DELTA', DELTA)):
        print('%s charge=%+.1f periods per circuit  at (%.2f, %.2f) -> torso px (%.1f, %.1f)'
              % (nm, q, fx, fy, fx * 12, fy * 19))



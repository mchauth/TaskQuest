def frame_dump():
    print('== ONE REAL POSE PER CLASS  ("O" bead, "|" rod, "=" witness, "-" field)')
    for cls in ('warrior', 'ranger', 'mage'):
        cfg = SLOTS['chest']
        stem = cfg['srcs'][cls]
        base = load_any('%s.png' % stem)
        for fi, sl, a in frames_of(base):
            got = compose(a, cls, None, '%s|%d' % (stem, fi))
            if got is None:
                continue
            rods, vals = got
            rod, bead, dark = paint(a, rods, vals)
            shares = recover(a, rod, bead)
            k = K[cls]
            subs = sorted({lagrange0(list(s)) for s in itertools.combinations(shares, k)})
            ys, xs = np.nonzero(a)
            print('== %s chest frame %d   shares %s   k=%d   every %d of them -> secret %s'
                  % (cls, fi, shares, k, k, subs))
            for sub in itertools.combinations(shares, k - 1):
                surv = surviving_secrets(list(sub), k)
                print('   below quorum %-22s -> still possible: %s'
                      % (str(list(sub)), sorted(surv)))
                break
            for y in range(ys.min(), ys.max() + 1):
                row = ''
                for x in range(xs.min(), xs.max() + 1):
                    if not a[y, x]:
                        row += '.'
                    elif bead[y, x]:
                        row += 'O'
                    elif rod[y, x]:
                        row += '|'
                    elif dark[y, x]:
                        row += '='
                    else:
                        row += '-'
                print('   ' + row)
            break


def survive():
    """Does the relief still read after the finishing pass? Reported, never a clause, and measured
    as LOCAL contrast - the finishing pass lays a cosine ramp over the whole sheet, so a bead on the
    shadowed flank is darker in absolute terms than the field on the lit one."""
    print('== SURVIVAL through the finishing pass (reported, local contrast)')
    for kind, cfg in SLOTS.items():
        tot = ok = 0
        for cls in cfg['srcs']:
            stem = cfg['srcs'][cls]
            base = load_any('%s.png' % stem)
            if not sheet_carries(base, cls, stem):
                continue
            arr, _ = build(base, cls, stem)
            fin, _i = finish_array(arr.copy(), '_tmp/%s_%s.png' % (cfg['dst'] % cls, kind))
            for fi, sl, a in frames_of(base):
                _fr, got = one_plate(base, sl, a, cls, None, '%s|%d' % (stem, fi))
                if got is None:
                    continue
                rod, bead, dark, _v = got
                lum = fin[sl][..., :3].astype(np.float64).sum(-1)
                for y, x in np.argwhere(rod | bead):
                    nb = [lum[ny, nx] for ny, nx in
                          ((y - 1, x), (y + 1, x), (y, x - 1), (y, x + 1))
                          if 0 <= ny < FH and 0 <= nx < FW and dark[ny, nx]]
                    if not nb:
                        continue
                    tot += 1
                    if lum[y, x] > float(np.mean(nb)):
                        ok += 1
        print('   %-7s crest still lighter than its own witness: %5d/%-5d (%3d%%)'
              % (kind, ok, tot, (100 * ok // tot) if tot else 0))



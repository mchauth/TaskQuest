def resorted_probe():
    """WHY THE TWO RANK CONTROLS CANNOT CATCH EVERYTHING, AND WHY THAT IS TWO THEOREMS RATHER THAN
    TWO WEAK CONTROLS. Both were written to show that the rank is not decoration. Between them they
    found two facts about this axis that nobody put there.

    (i) REVERSAL IS A REFLECTION, AND ONLY THAT. Four rods means the abscissae are 1, 2, 3, 4, and
        reversing them sends x to 5 - x, which in GF(5) IS -x. The reversed plate therefore carries
        g(x) = f(-x), and a polynomial and its own reflection have the same constant term. So the
        secret survives reversal exactly, on every four-rod plate of every class. THE CONTROL DID
        NOT FAIL TO FIND A DIFFERENCE; THERE IS NO DIFFERENCE TO FIND, and what it turned up instead
        is that a full plate may be read from either end of its rank and says the same thing twice.

    (ii) THE WARRIOR IS RANK-BLIND ALTOGETHER, AND IS THE ONLY CLASS THAT IS. Over GF(5) the powers
        x^0, x^1, x^2, x^3 each sum to zero across the whole field, so for any f of degree at most
        three f(0) + f(1) + f(2) + f(3) + f(4) = 0. The warrior draws four rods and needs all four,
        so its shares are f(1..4) and its secret is MINUS THEIR SUM. A sum does not care what order
        it is written in - SO EVERY PERMUTATION OF A WARRIOR'S RODS RECONSTRUCTS THE SAME SECRET,
        not just the reversal, and no control that only moves rods about can ever catch a warrior.

    This is worth more than the controls it costs. The warrior's plate, which is the one whose
    quorum is the whole plate, is not really a threshold scheme at all: it is a CHECKSUM, and its
    law reads "the four beads sum to two". That is what k = n = P-1 means, and it is a limit of the
    construction rather than a defect in it - clause IGNORANCE is untouched, three rods still leave
    four secrets standing, and the plate is exactly as private as it claims. The mage and the ranger
    keep fewer rods than they could and so keep their order mattering; the warrior spends its order
    on its threshold. NOBODY DESIGNED THAT ASYMMETRY AND THE FILE WOULD RATHER NAME IT THAN LEAVE
    IT FOR SOMEBODY TO FIND."""
    print('== THE RANK CONTROLS, EXPLAINED  (what RESORTED and CYCLED cannot catch, and why)')
    print('   (i)  reversing n rods sends x -> (n+1) - x; at n = 4 that is x -> -x in GF(5), and')
    print('        f(-x) has the same constant term as f(x). The secret cannot move.')
    print('   (ii) sum_{x in GF(5)} x^j = 0 for j <= 3, so a warrior (k = n = 4) has secret')
    print('        -(sum of its beads) - AND A SUM HAS NO ORDER. Every permutation reconstructs.')
    print('   %-7s %-8s %-9s %-14s %s' % ('slot', 'class', 'plates', 'reversal same', 'ALL 24'
                                          ' permutations same'))
    for kind, cfg in SLOTS.items():
        for cls in cfg['srcs']:
            stem = cfg['srcs'][cls]
            base = load_any('%s.png' % stem)
            same = tot = allperm = 0
            for fi, sl, a in frames_of(base):
                got = compose(a, cls, None, '%s|%d' % (stem, fi))
                if got is None:
                    continue
                _rods, vals = got
                tot += 1
                k = K[cls]
                base_s = lagrange0([(i + 1, v) for i, v in enumerate(vals)][:k])
                rev = [(i + 1, v) for i, v in enumerate(vals[::-1])]
                if lagrange0(rev[:k]) == base_s:
                    same += 1
                if all(lagrange0([(i + 1, v) for i, v in enumerate(pm)][:k]) == base_s
                       for pm in itertools.permutations(vals)):
                    allperm += 1
            if tot:
                print('   %-7s %-8s %-9d %-14s %s'
                      % (kind, cls, tot, '%d/%d' % (same, tot), '%d/%d' % (allperm, tot)),
                      flush=True)



def put(fr, y, x, rgb):
    if 0 <= y < fr.shape[0] and 0 <= x < fr.shape[1]:
        fr[y, x, :3] = rgb
        fr[y, x, 3] = 255


def recolor(src, fr, a, D, M, L):
    v = src[..., :3].astype(np.float32).max(-1) / 255.0
    vref = float(np.median(v[a]))
    ratio = v / max(vref, 1e-3)
    for y, x in np.argwhere(a):
        q = ratio[y, x]
        tone = D if q < Q_LO else (L if q > Q_HI else M)
        put(fr, y, x, tone)


# --- the arithmetic of a secret ----------------------------------------------------------------
def ev(coefs, x):
    """A polynomial over GF(5) at a point."""
    out = 0
    for c in reversed(coefs):
        out = (out * x + c) % P
    return out


def inv(x):
    return pow(x % P, P - 2, P)


def lagrange0(points):
    """The value at ZERO of the unique polynomial of degree < len(points) through them. THE SECRET
    LIVES AT x = 0 AND THERE IS NO ROD AT x = 0: the one thing every plate in this wardrobe is
    about is the one place the ornament deliberately leaves empty."""
    s = 0
    for i, (xi, yi) in enumerate(points):
        num = den = 1
        for j, (xj, _) in enumerate(points):
            if i == j:
                continue
            num = (num * (-xj)) % P
            den = (den * (xi - xj)) % P
        s = (s + yi * num * inv(den)) % P
    return s


def interp_coefs(points):
    """Coefficients, low order first, of the interpolating polynomial over GF(5)."""
    n = len(points)
    coefs = [0] * n
    for i, (xi, yi) in enumerate(points):
        basis = [1]
        den = 1
        for j, (xj, _) in enumerate(points):
            if i == j:
                continue
            nxt = [0] * (len(basis) + 1)
            for d, c in enumerate(basis):
                nxt[d] = (nxt[d] - c * xj) % P
                nxt[d + 1] = (nxt[d + 1] + c) % P
            basis = nxt
            den = (den * (xi - xj)) % P
        scale = (yi * inv(den)) % P
        for d, c in enumerate(basis):
            coefs[d] = (coefs[d] + c * scale) % P
    return coefs


def degree_of(coefs):
    d = -1
    for i, c in enumerate(coefs):
        if c % P:
            d = i
    return d


def deal(k, n, salt):
    """Pick the polynomial, then read the beads off it. THE PAINTER DEALS AND DOES NOT SEARCH: the
    constant term is the secret because it must be, the top coefficient is non-zero because clause
    DEGREE says so, and everything between is free and hashed from the plate's own name - which is
    why two poses of the same garment hold different shares while the male and female sheets of one
    pose hold the same ones."""
    h = hashlib.md5(('%s|%d|%d' % (salt, k, n)).encode()).digest()
    coefs = [SECRET] + [0] * (k - 1)
    for j in range(1, k - 1):
        coefs[j] = h[j] % P
    if k >= 2:
        coefs[k - 1] = 1 + (h[0] % (P - 1))       # never zero: the degree is exactly k-1
    return coefs, [ev(coefs, i + 1) for i in range(n)]


def surviving_secrets(sub, k):
    """CLAUSE IGNORANCE, DONE BY COUNTING RATHER THAN BY FAILING TO GUESS. For each candidate
    secret t, how many polynomials of degree EXACTLY k-1 pass through these k-1 shares and take the
    value t at zero? Returns {t: count}. Perfect secrecy would put a 1 against all five; requiring
    the degree be exactly k-1 kills exactly one candidate, because the leading coefficient of the
    completion is an affine function of t with a non-zero slope. Four survive, one plate apiece,
    and that is the honest strength of the plate: ONE GUESS IN FOUR."""
    out = {}
    for t in range(P):
        pts = [(0, t)] + list(sub)
        c = interp_coefs(pts)
        if degree_of(c) == k - 1:
            out[t] = out.get(t, 0) + 1
    return out


# --- the construction --------------------------------------------------------------------------
def rim_of(a):
    """The pixels where the piece stops and the world starts."""
    h, w = a.shape
    rim = np.zeros_like(a)
    for y, x in np.argwhere(a):
        for dy, dx in NB4:
            ny, nx = y + dy, x + dx
            if not (0 <= ny < h and 0 <= nx < w) or not a[ny, nx]:
                rim[y, x] = True
                break
    return rim


def anchors_of(mask, n):
    """Farthest-point sampling: n pixels of the mask as far from one another as the mask allows.
    Ordering by distance from the centroid gives several starts in the same corner, which is one
    attempt repeated - the 70th paid for that lesson and this axis inherits the fix.

    THE SAMPLING STARTS AT THE MIDDLE AND NOT AT AN EXTREMITY, which is a matter of looks rather
    than of law. The first draft seeded itself with the pixel FURTHEST from the centroid, and
    farthest-point sampling faithfully carried on from there: every rod ended up pinned to the
    outline, and a five-pixel line lying along a silhouette does not read as ornament at all - it
    reads as a ragged edge. Seeded from the middle the same routine spreads the rods ACROSS THE
    GARMENT, which is where a reader looks for them."""
    pts = [(int(y), int(x)) for y, x in np.argwhere(mask)]
    if not pts:
        return []
    ys, xs = np.nonzero(mask)
    cy, cx = ys.mean(), xs.mean()
    out = [min(pts, key=lambda p: ((p[0] - cy) ** 2 + (p[1] - cx) ** 2, p[0], p[1]))]
    while len(out) < n and len(out) < len(pts):
        out.append(max((p for p in pts if p not in out),
                       key=lambda p: (min((p[0] - q[0]) ** 2 + (p[1] - q[1]) ** 2 for q in out),
                                      -p[0], -p[1])))
    return out


def grow(a, blocked, start, d):
    """One rod: five pixels, straight, evenly stepped. A bent rod's bend is a pixel the reader would
    have to call either a step or a corner and cannot, and a rod of any other length is not a
    number in GF(5) - so the length is not a taste, it is the field."""
    y, x = start
    px = []
    for _ in range(ROD):
        if not (0 <= y < a.shape[0] and 0 <= x < a.shape[1]):
            return None
        if not a[y, x] or blocked[y, x]:
            return None
        px.append((y, x))
        y, x = y + d[0], x + d[1]
    return px


def block(blocked, px, tight=False):
    """Rods are kept a pixel apart so the reader can tell them from one another - clause CLEAR. Two
    touching rods are one crest component, and one component of ten pixels is not a share, it is a
    smudge the reader refuses. Control CROWDED is exactly this line switched off."""
    h, w = blocked.shape
    ring = ((0, 0),) if tight else ((0, 0),) + NB8
    for (y, x) in px:
        for dy, dx in ring:
            ny, nx = y + dy, x + dx
            if 0 <= ny < h and 0 <= nx < w:
                blocked[ny, nx] = True


def rods_of(a, nwant, skip=0, tight=False):
    """THE SHARES ARE SPREAD OVER THE WHOLE PLATE, NOT OVER EACH PART. A secret split across a suit
    of two greaves is one secret; either greave alone is below quorum and knows nothing, which is
    the axis stating its own law about its own halves."""
    parts = parts_of(a)
    if not parts:
        return []
    body = np.zeros_like(a)
    for c in parts:
        body |= c
    # PREFER THE INSIDE OF THE GARMENT. A rod that runs along the silhouette is read by the reader
    # perfectly well and looked wrong every time; the pool is drawn from the pixels that are not on
    # the outline. THE FALLBACK IS TRIED ONLY WHEN THE INSIDE HAS ALREADY FAILED, not guessed at in
    # advance by an area test - a sabaton can have enough interior pixels and still have no five of
    # them in a line, and guessing cost the female ranger's boots two poses and the whole sheet.
    inner = body & ~rim_of(body)
    for pool_mask in (inner, body):
        blocked = np.zeros_like(a)
        out = []
        pool = anchors_of(pool_mask, max(12, nwant * 8))
        pool = pool[skip:] + pool[:skip]
